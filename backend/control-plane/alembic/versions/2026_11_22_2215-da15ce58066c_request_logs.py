DROP_PARTITIONS = r"""
    CREATE FUNCTION drop_request_log_partitions(keep_days integer) RETURNS integer
    LANGUAGE plpgsql SECURITY DEFINER SET search_path TO pg_catalog, public, pg_temp AS $$
    DECLARE
        part record;
        month date;
        dropped integer := 0;
    BEGIN
        IF keep_days IS NULL OR keep_days < 1 THEN
            RAISE EXCEPTION 'keep_days must be at least 1';
        END IF;
        PERFORM pg_advisory_xact_lock(hashtext('request_logs_partitions'));
        FOR part IN
            SELECT c.relname FROM pg_inherits i JOIN pg_class c ON c.oid = i.inhrelid
             WHERE i.inhparent = 'public.request_logs'::regclass
               AND c.relname ~ '^request_logs_y\d{4}m\d{2}$'
        LOOP
            month := to_date(substr(part.relname, 14), '"y"YYYY"m"MM');
            -- Dropped once its newest row is older than keep_days.
            IF (month + interval '1 month')::timestamp AT TIME ZONE 'UTC'
               <= now() - make_interval(days => keep_days) THEN
                EXECUTE format('DROP TABLE public.%I', part.relname);
                dropped := dropped + 1;
            END IF;
        END LOOP;
        RETURN dropped;
    END;
    $$
"""


